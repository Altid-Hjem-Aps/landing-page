#!/usr/bin/env python3
"""Renders the new front page's own backgrounds into public/site/render (ALT-1420).

One-off tool, run by hand, not part of the build. Needs numpy, scipy, Pillow and ffmpeg.

Usage: site-render.py <tunnel|clouds|spotlight|all>
"""
import base64
import io
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "site" / "render"
POSTER_CSS = ROOT / "app" / "site-tunnel-poster.css"

CREAM = (253, 250, 244)
MINT = (120, 226, 150)
HONEY = (255, 205, 112)
ROSE = (255, 170, 176)
LAVENDER = (176, 160, 250)
SKY = (112, 196, 255)
WHITE = (255, 253, 248)
# The hero panel's gradient at the video's top and bottom. Same numbers as .h-sky.
PANEL_TOP = np.array((217, 233, 250), dtype=np.float32)
PANEL_BOTTOM = np.array((253, 250, 244), dtype=np.float32)

# Colour across the bundle of light: t runs from -1 (top edge) to 1 (bottom edge).
STOPS = [
    (-1.3, SKY, 0.0),
    (-1.02, SKY, 0.34),
    (-0.74, MINT, 0.42),
    (-0.48, HONEY, 0.4),
    (-0.26, ROSE, 0.52),
    (-0.06, WHITE, 0.62),
    (0.14, ROSE, 0.46),
    (0.36, LAVENDER, 0.46),
    (0.62, SKY, 0.62),
    (0.9, MINT, 0.38),
    (1.28, MINT, 0.0),
]
WIDTH, HEIGHT, FPS, SECONDS = 1280, 720, 24, 6


def tileable_streaks(seed: int, rows: int = 720, cols: int = 1024) -> np.ndarray:
    """Noise that is thin across and long along, and wraps along: light streaks."""
    rng = np.random.default_rng(seed)
    noise = rng.standard_normal((rows, cols))
    fine = ndimage.gaussian_filter(noise, sigma=(0.9, 60), mode=("reflect", "wrap"))
    coarse = ndimage.gaussian_filter(rng.standard_normal((rows, cols)), sigma=(5, 120), mode=("reflect", "wrap"))
    fine /= fine.std()
    coarse /= coarse.std()
    return (0.7 * fine + 0.3 * coarse).astype(np.float32)


def colour_ramp(t: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    xs = [s[0] for s in STOPS]
    rgb = np.stack([np.interp(t, xs, [s[1][c] for s in STOPS]) for c in range(3)], -1)
    return rgb.astype(np.float32), np.interp(t, xs, [s[2] for s in STOPS]).astype(np.float32)


def tunnel_frame(index: int, frames: int, layers: list[np.ndarray]) -> np.ndarray:
    y, x = np.mgrid[0:HEIGHT, 0:WIDTH].astype(np.float32)
    u = (x + 0.5) / WIDTH * 2 - 1
    v = (y + 0.5) / HEIGHT * 2 - 1
    away = np.abs(u)
    # The bundle pinches in the middle and flares towards both sides.
    half = 0.13 + 0.42 * away**1.9
    centre = 0.0 - 0.03 * (1 - away**2)
    t = (v - centre) / half
    rgb, alpha = colour_ramp(t)
    phase = index / frames
    row = np.clip((t + 1.4) / 2.8, 0, 1) * (layers[0].shape[0] - 1)
    streak = np.zeros_like(t)
    for number, layer in enumerate(layers):
        # Streaks run outwards from the middle, faster the further out they are.
        along = away**0.8 * layer.shape[1] * (0.9 + 0.5 * number) - phase * layer.shape[1] * (number + 1)
        sampled = ndimage.map_coordinates(layer, [row, along % layer.shape[1]], order=1, mode="grid-wrap")
        streak += sampled * (0.65 if number == 0 else 0.35)
    # Streaks fade in from the pinch and ease off at the far edges.
    presence = np.clip(away / 0.22, 0, 1) * (1 - 0.35 * away**3)
    lit = np.clip(streak, -2.4, 2.8) * presence
    alpha = np.clip(alpha * (1 + 0.42 * lit), 0, 1)
    highlight = np.clip((lit - 0.75) / 1.6, 0, 1)[..., None]
    rgb = rgb * (1 - 0.85 * highlight) + np.array(WHITE, dtype=np.float32) * 0.85 * highlight
    alpha = np.maximum(alpha, highlight[..., 0] * alpha * 1.15)
    # The bundle dies out towards the panel's sides.
    alpha = alpha * (1 - 0.8 * np.clip((away - 0.68) / 0.32, 0, 1) ** 2)
    # A slight softening keeps the bands from reading as a chart.
    alpha = ndimage.gaussian_filter(alpha, 0.8)
    panel = PANEL_TOP + (PANEL_BOTTOM - PANEL_TOP) * ((y + 0.5) / HEIGHT)[..., None]
    out = panel * (1 - alpha[..., None]) + rgb * alpha[..., None]
    return np.clip(out + 0.5, 0, 255).astype(np.uint8)


def write_tunnel_poster(frame: Image.Image) -> None:
    buffer = io.BytesIO()
    frame.convert("RGB").resize((1024, 576), Image.LANCZOS).save(buffer, "WEBP", quality=45, method=6)
    data = base64.b64encode(buffer.getvalue()).decode()
    POSTER_CSS.write_text(
        "/* Generated by scripts/site-render.py from the tunnel's first frame. Inline so the page's\n"
        "   largest picture arrives with the stylesheet, without a download of its own on a phone. */\n"
        f".h-tunnel-wrap {{\n  background: center / cover no-repeat url(data:image/webp;base64,{data});\n}}\n"
    )


def build_tunnel() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    frames = FPS * SECONDS
    layers = [tileable_streaks(11), tileable_streaks(23)]
    with tempfile.TemporaryDirectory() as folder:
        for i in range(frames):
            Image.fromarray(tunnel_frame(i, frames, layers)).save(f"{folder}/{i:04d}.png", compress_level=1)
            if i == 0:
                write_tunnel_poster(Image.open(f"{folder}/0000.png"))
        source = ["-y", "-hide_banner", "-loglevel", "error", "-framerate", str(FPS), "-i", f"{folder}/%04d.png", "-an"]
        subprocess.run(["ffmpeg", *source, "-c:v", "libvpx-vp9", "-crf", "33", "-b:v", "0", "-row-mt", "1", "-pix_fmt", "yuv420p", str(OUT / "tunnel.webm")], check=True)
        subprocess.run(["ffmpeg", *source, "-c:v", "libx264", "-crf", "23", "-preset", "slow", "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(OUT / "tunnel.mp4")], check=True)
    for name in ("tunnel.webm", "tunnel.mp4"):
        print(name, (OUT / name).stat().st_size)


def fbm(shape: tuple[int, int], seed: int, stretch: float = 1.6) -> np.ndarray:
    rng = np.random.default_rng(seed)
    total = np.zeros(shape, dtype=np.float64)
    amplitude = 1.0
    for sigma in (90, 45, 22, 11, 5, 2.5):
        layer = ndimage.gaussian_filter(rng.standard_normal(shape), sigma=(sigma, sigma * stretch), mode="wrap")
        total += amplitude * layer / layer.std()
        amplitude *= 0.58
    return (total - total.min()) / (total.max() - total.min())


def build_clouds() -> None:
    """Soft cream clouds, alpha only: the sky itself is the panel's gradient."""
    OUT.mkdir(parents=True, exist_ok=True)
    width, height = 1424, 338
    noise = fbm((height, width), 7)
    edge = np.clip((noise - 0.44) / 0.26, 0, 1)
    edge = edge * edge * (3 - 2 * edge)
    fade = np.clip(1 - (np.arange(height) / height) ** 1.4, 0, 1)[:, None]
    # Keep the middle, behind the headline, lighter than the sides.
    across = 0.55 + 0.45 * np.abs(np.linspace(-1, 1, width))[None, :] ** 1.2
    alpha = edge * fade * across * 0.92
    rgba = np.dstack([np.full((height, width), c, dtype=np.uint8) for c in (255, 253, 248)] + [np.round(alpha * 255).astype(np.uint8)])
    Image.fromarray(rgba).save(OUT / "clouds.webp", "WEBP", quality=70, alpha_quality=60, method=6)
    print("clouds.webp", (OUT / "clouds.webp").stat().st_size)


def build_spotlight() -> None:
    """A soft cone of light from the top edge. Alpha only, so it sits on Deep forest."""
    OUT.mkdir(parents=True, exist_ok=True)
    width, height = 688, 495
    y, x = np.mgrid[0:height, 0:width].astype(np.float64)
    u = (x + 0.5 - width / 2) / (width / 2)
    v = (y + 0.5) / height
    spread = 0.06 + 0.62 * v**1.1
    cone = np.exp(-((u / spread) ** 2))
    fall = (1 - v) ** 1.5
    core = np.exp(-((u / (0.02 + 0.16 * v)) ** 2)) * (1 - v) ** 3
    alpha = np.clip(0.42 * cone * fall + 0.3 * core, 0, 1)
    # Dithered and stored without loss: a smooth ramp this faint bands badly in 8 bits.
    noise = np.random.default_rng(7).random((height, width)) - 0.5
    channel = np.clip(np.round(alpha * 255 + noise * 1.5), 0, 255).astype(np.uint8)
    rgba = np.dstack([np.full((height, width), c, dtype=np.uint8) for c in (232, 240, 226)] + [channel])
    Image.fromarray(rgba).save(OUT / "spotlight.webp", "WEBP", lossless=True, method=6)
    print("spotlight.webp", (OUT / "spotlight.webp").stat().st_size)


STEPS = {"tunnel": build_tunnel, "clouds": build_clouds, "spotlight": build_spotlight}

if __name__ == "__main__":
    step = sys.argv[1]
    for run in STEPS.values() if step == "all" else [STEPS[step]]:
        run()
