// Builds public/site/ and components/site/plates.ts for the front page from the
// capture folders on the Mac that holds them. Run by hand when a capture
// changes: `node scripts/site-assets.mjs`. Output is committed; the sources are
// not, and the app has no build step that needs them.
//

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'
import sharp from 'sharp'

const HOME = homedir()
const CAPTURES = join(HOME, 'altid-worktrees/site-captures/2026-11-04/sim')
const FOOD = join(HOME, 'altid-worktrees/alt-1420-facilpay-shots/food')
const PAINTINGS = join(HOME, 'altid-hjem-app-worktrees/site-captures/assets/images/hjem/dreams/3.0x')
const PACK = 'public/brand-kuqbnes0j3n6zg/logo-pack'
const OUT = 'public/site'

const SCREEN_WIDTH = 780
const SCREEN_QUALITY = 82

const SCREENS = [
  'hjem/hjem.top',
  'okonomi/okonomi.top',
  'okonomi/droemme.detail',
  'okonomi/regninger.top',
  'mad/mad.home',
  'mad/mad.trip.in_progress',
  'energi/energi.home',
  'forsikring/b.flow.3_insurances_chosen',
  'forsikring/b.forlob.waiting',
]

// The card that breaks out of the phone: full-resolution top of hjem.top, from
// under the Mine/Fælles toggle down past the bars. No status bar, no beta pill.
const HERO_CROP = { left: 0, top: 340, width: 1179, height: 520 }

const LARGE_PLATES = new Set(['kylling-i-karry', 'hjemmelavet-pizza', 'butter-chicken', 'klassiske-tacos'])

const FOLD = { æ: 'ae', ø: 'oe', å: 'aa', é: 'e' }

// The file name is the dish before its "med ...": "Butter chicken med ris og
// naan" is butter-chicken.
function plateSlug(name) {
  return name
    .split(' med ')[0]
    .toLowerCase()
    .replace(/[æøåé]/g, (c) => FOLD[c])
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

async function screens() {
  await mkdir(join(OUT, 'screens'), { recursive: true })
  for (const path of SCREENS) {
    const name = path.split('/')[1]
    await sharp(join(CAPTURES, `${path}.png`))
      .resize({ width: SCREEN_WIDTH })
      .webp({ quality: SCREEN_QUALITY })
      .toFile(join(OUT, 'screens', `${name}.webp`))
  }
  await sharp(join(CAPTURES, 'hjem/hjem.top.png'))
    .extract(HERO_CROP)
    .webp({ quality: 90, smartSubsample: true })
    .toFile(join(OUT, 'hjem-hero-crop.webp'))
}

async function plates() {
  await mkdir(join(OUT, 'plates'), { recursive: true })
  const dishes = JSON.parse(await readFile(join(FOOD, 'alpha.json'), 'utf8'))
  const rows = []
  for (const [name, file] of dishes) {
    const slug = plateSlug(name)
    if (rows.some((r) => r.slug === slug)) throw new Error(`two plates named ${slug}`)
    await sharp(file).resize({ width: 480 }).webp({ quality: 80, alphaQuality: 90 }).toFile(join(OUT, 'plates', `${slug}.webp`))
    const row = { name, slug, src: `/site/plates/${slug}.webp` }
    if (LARGE_PLATES.has(slug)) {
      await sharp(file).resize({ width: 800 }).webp({ quality: 80, alphaQuality: 90 }).toFile(join(OUT, 'plates', `${slug}-800.webp`))
      row.src800 = `/site/plates/${slug}-800.webp`
    }
    rows.push(row)
  }
  for (const slug of LARGE_PLATES) {
    if (!rows.some((r) => r.slug === slug)) throw new Error(`large plate ${slug} is not in alpha.json`)
  }
  const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')
  await writeFile(
    'components/site/plates.ts',
    `// Generated by scripts/site-assets.mjs. Real dishes from the Altid Mad catalog,
// cut out on transparent, square. Every plate has a 480 px file; four also 800 px.

export type PlateData = { name: string; slug: string; src: string; src800?: string }

export const PLATES: PlateData[] = [
${body}
]
`,
  )
}

async function paintings() {
  await mkdir(join(OUT, 'painting'), { recursive: true })
  await sharp(join(PAINTINGS, 'coast_colour.png')).webp({ quality: 82 }).toFile(join(OUT, 'painting', 'coast-colour.webp'))
  await sharp(join(PAINTINGS, 'coast_line.png')).webp({ quality: 88 }).toFile(join(OUT, 'painting', 'coast-line.webp'))
}

