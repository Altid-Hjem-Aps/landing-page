async function icons() {
  await mkdir(join(OUT, 'icons'), { recursive: true })
  for (const name of ['madplan', 'strom', 'forsikring']) {
    await copyFile(join(PACK, 'service-icons', `${name}-circle.svg`), join(OUT, 'icons', `${name}.svg`))
  }
  await writeFile(join(OUT, 'icons', 'okonomi.svg'), OKONOMI_CIRCLE)
  await copyFile(join(PACK, 'app-icon', 'altid-hjem-app-icon-rounded.svg'), join(OUT, 'icons', 'app-icon.svg'))
  await copyFile(join(PACK, 'sub-brands', 'altid-energi-logo.svg'), join(OUT, 'icons', 'altid-energi.svg'))
}

